const BASE = "https://example.com/schemas/v1/";
const ROOT = "/project";

/** Characters that are hard to see or end markup, made from code points so no file holds them raw. */
const ODD = {
  lineSeparator: String.fromCodePoint(0x2028),
  bom: String.fromCodePoint(0xfeff),
  nul: String.fromCodePoint(0),
  bidi: String.fromCodePoint(0x202e),
  astral: String.fromCodePoint(0x1f600),
  zeroWidth: String.fromCodePoint(0x200b),
  joiner: String.fromCodePoint(0x200d),
  wordJoiner: String.fromCodePoint(0x2060),
  softHyphen: String.fromCodePoint(0xad),
};

/** A description that tries every way of breaking out of Markdown and HTML. */
const HOSTILE = [
  "# not a title",
  "<script>alert(1)</script> & &amp; <b>bold</b>",
  "a | b | c and `tick` and *em* and _em_ and [link](https://example.com) and ![img](x.png)",
  "    indented like code",
  "1. not a list",
  "- not a list either",
  "> not a quote",
  "===",
  `odd${ODD.lineSeparator}line${ODD.bom}bom${ODD.nul}nul${ODD.bidi}bidi ${ODD.astral}`,
  `zw${ODD.zeroWidth}zj${ODD.joiner}wj${ODD.wordJoiner}sh${ODD.softHyphen}y`,
  "\"quotes\" and 'apostrophes' and </code></pre></td></table>",
].join("\n");

const HOSTILE_KEY = "a|b`c</code>";
const HOSTILE_PATTERN = "^(?:x|`|<)$";

function orderSchema(): JsonObject {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: `${BASE}order.json`,
    title: "Order",
    description: HOSTILE,
    type: "object",
    properties: {
      id: { description: "The order id.", type: "string", minLength: 3, maxLength: 8 },
      [HOSTILE_KEY]: { description: HOSTILE, type: "string", pattern: HOSTILE_PATTERN },
      status: { $ref: "#/$defs/status" },
      lines: { type: "array", items: { $ref: "#/$defs/line" }, maxItems: 2 },
      payment: { $ref: "#/$defs/payment" },
    },
    required: ["id", "status"],
    additionalProperties: false,
    $defs: {
      status: { description: "Where the order is.", enum: ["open", `pa|d<${ODD.bom}>`, "`x`"] },
      line: {
        type: "object",
        properties: { sku: { type: "string" }, count: { type: "integer", minimum: 1, multipleOf: 2 } },
        required: ["sku", "count"],
        additionalProperties: false,
      },
      payment: {
        oneOf: [
          {
            type: "object",
            properties: { type: { const: "card" }, last4: { type: "string", pattern: "^\\d{4}$" } },
            required: ["type", "last4"],
            additionalProperties: false,
          },
          {
            type: "object",
            properties: { type: { const: "bank" } },
            required: ["type"],
            additionalProperties: false,
          },
        ],
      },
    },
  };
}

function model(): Model {
  return buildModel(schemaSet({ order: orderSchema() }));
}

function config(format: "markdown" | "html" = "markdown", targets: object = { rust: { out: "rs" }, go: { out: "go" }, typescript: { out: "ts" } }): Config {
  return parseConfig({ targets, docs: { out: "docs/types", format } }, join(ROOT, "strictgen.json"));
}

/** The text of every generated file, by name. */
function files(format: "markdown" | "html"): Map<string, string> {
  return new Map(docsFiles(config(format), model(), format).map((f) => [f.path.replace(/^docs\/types\//, ""), f.contents]));
}

const RAW_HIDDEN = new RegExp(
  `[${ODD.lineSeparator}${ODD.bom}${ODD.nul}${ODD.bidi}${ODD.zeroWidth}${ODD.joiner}${ODD.wordJoiner}${ODD.softHyphen}]`,
  "u",
);

describe("docs markdown pages", () => {
  const pages = files("markdown");
  const order = pages.get("Order.md") ?? "";

  it("writes one page per type and an index, each starting with the header", () => {
    expect([...pages.keys()].sort()).toEqual(
      [DOCS_INDEX, "Line.md", "Order.md", "Payment.md", "PaymentBank.md", "PaymentBankType.md", "PaymentCard.md", "PaymentCardType.md", "Status.md"].sort(),
    );
    for (const text of pages.values()) {
      expect(text.startsWith(`${markupHeader("Code generated by strictgen. DO NOT EDIT.")}\n`)).toBe(true);
      expect(isGenerated(text)).toBe(true);
    }
  });

  it("shows description, fields, each configured language's type, constraints and an example", () => {
    expect(order).toContain("# Order\n");
    expect(order).toContain("| Key | Type | Required | Rust | Go | TypeScript | Constraints | Description |");
    expect(order).toContain("| `id` | string | yes | `String` | `string` | `string` | 3 to 8 characters | The order id. |");
    expect(order).toContain("| `lines` | array of [Line](Line.md) | no | `Option<Vec<Line>>` | `*[]Line` | `Line[]` | at most 2 items |");
    expect(order).toContain("| `payment` | [Payment](Payment.md) | no | `Option<Payment>` | `Payment` | `Payment` |");
    expect(order).toContain("## Example\n\n```json\n{");
    expect(pages.get("Line.md")).toContain("\\>= 1; a multiple of 2");
    expect(pages.get("Payment.md")).toContain("| `\"card\"` | [PaymentCard](PaymentCard.md) |");
    expect(pages.get("Status.md")).toContain("- `\"pa|d<\\u{feff}>\"`");
  });

  it("shows only the configured languages", () => {
    const only = docsFiles(config("markdown", { go: { out: "go" } }), model(), "markdown");
    const text = only.find((f) => f.path.endsWith("/Order.md"))?.contents ?? "";
    expect(text).toContain("| Key | Type | Required | Go | Constraints | Description |");
    expect(text).not.toContain("Rust");
  });

  it("links the types a type uses and the types that use it", () => {
    expect(order).toContain("- Uses: [Line](Line.md), [Payment](Payment.md), [Status](Status.md)");
    expect(pages.get("Line.md")).toContain("- Used by: [Order](Order.md)");
    expect(pages.get(DOCS_INDEX)).toContain("- [Order](Order.md): # not a title");
  });

  it("escapes schema text so it never becomes markup", () => {
    for (const text of pages.values()) {
      expect(text).not.toMatch(RAW_HIDDEN);
      expect(text).not.toContain("<script>");
      expect(text).not.toContain("<b>");
      // Outside the header comment and the example, no line is raw HTML, an indented code block, a quote or a list we didn't write.
      const prose = text.replace(/```json\n[\s\S]*?\n```/g, "");
      for (const line of prose.split("\n").slice(1)) {
        expect(line).not.toMatch(/^ {4}/);
        expect(line).not.toMatch(/^(?:<|>|1\.|===)/);
        if (line.startsWith("- ")) expect(line).toMatch(/^- (?:Uses|Used by|\[|`)/);
        if (line.startsWith("#")) expect(line).toMatch(/^#{1,2} [A-Za-z]/);
      }
    }
    expect(order).toContain("\\# not a title");
    expect(order).toContain("\\<script\\>alert(1)\\</script\\> \\& \\&amp;");
    expect(order).toContain("a \\| b \\| c and \\`tick\\` and \\*em\\* and \\_em\\_ and \\[link\\](https://example.com) and \\!\\[img\\](x.png)");
    expect(order).toContain("\nindented like code\n1\\. not a list\n\\- not a list either\n\\> not a quote\n\\===\n");
    expect(order).toContain("odd\\\\u{2028}line\\\\u{feff}bom\\\\u{0}nul\\\\u{202e}bidi \u{1f600}");
    expect(order).toContain("zw\\\\u{200b}zj\\\\u{200d}wj\\\\u{2060}sh\\\\u{ad}y");
  });

  it("keeps every table row to its columns, whatever the cells hold", () => {
    for (const text of pages.values()) {
      for (const table of text.split("\n\n").filter((b) => b.startsWith("| "))) {
        // Cells split on pipes that no backslash escapes.
        const widths = table.split("\n").map((row) => row.split(/(?<!\\)\|/).length - 2);
        expect(new Set(widths).size).toBe(1);
      }
    }
    expect(order).toContain("| ``a\\|b`c</code>`` | string | no |");
    expect(order).toContain("| matching ``^(?:x\\|`\\|<)$`` |");
  });

  it("writes code spans that hold any text, with backticks and pipes", () => {
    expect(markdownCode("a`b", false)).toBe("``a`b``");
    expect(markdownCode("`a", false)).toBe("`` `a ``");
    expect(markdownCode("a|b", true)).toBe("`a\\|b`");
    expect(markdownCode(`x${ODD.lineSeparator}y`, false)).toBe("`x\\u{2028}y`");
    expect(markdownText("<a & b>")).toBe("\\<a \\& b\\>");
  });

  it("fails when two pages would differ only in case, as on a filesystem that ignores it", () => {
    const clash = buildModel(
      schemaSet({
        order: { ...orderSchema(), $defs: { ...(orderSchema().$defs as JsonObject), index: { type: "string" } } },
      }),
    );
    expect(() => docsFiles(config(), clash, "markdown")).toThrow(
      "Index.md: name-clash: the docs pages index.md and Index.md differ only in case",
    );
  });

  it("is the same on every run", () => {
    expect(files("markdown")).toEqual(pages);
  });
});

describe("docs html page", () => {
  const html = files("html").get(DOCS_HTML) ?? "";
  const pages = files("markdown");

  it("is one file that starts with the header, then the doctype", () => {
    expect([...files("html").keys()]).toEqual([DOCS_HTML]);
    expect(html.startsWith(`${markupHeader("Code generated by strictgen. DO NOT EDIT.")}\n<!doctype html>\n`)).toBe(true);
    expect(isGenerated(html)).toBe(true);
  });

  it("loads nothing from elsewhere and runs no script", () => {
    expect(html).not.toMatch(/<(?:script|link|img|iframe|object)\b/i);
    expect(html).not.toMatch(/\b(?:src|href)="(?!#)/);
    expect(html).not.toMatch(/url\(/);
  });

  it("has an anchor per type, and every link points at one", () => {
    const ids = new Set([...html.matchAll(/ id="([^"]+)"/g)].map((m) => m[1]));
    for (const name of [...pages.keys()].filter((n) => n !== DOCS_INDEX)) {
      expect(ids.has(`type-${name.replace(/\.md$/, "")}`)).toBe(true);
    }
    for (const [, target] of html.matchAll(/ href="#([^"]+)"/g)) expect(ids.has(target)).toBe(true);
  });

  it("escapes every piece of schema text", () => {
    expect(html).not.toMatch(RAW_HIDDEN);
    const tags = new Set([...html.matchAll(/<\/?([a-z0-9!-]+)/gi)].map((m) => (m[1] ?? "").toLowerCase()));
    const allowed = ["!--", "!doctype", "html", "head", "meta", "title", "style", "body", "main", "nav", "section", "h1", "h2", "h3", "p", "br", "ul", "li", "a", "div", "table", "thead", "tbody", "tr", "th", "td", "code", "pre"];
    for (const tag of tags) expect(allowed).toContain(tag);
    expect(html).toContain("&#60;script&#62;alert(1)&#60;/script&#62; &#38; &#38;amp; &#60;b&#62;bold&#60;/b&#62;");
    expect(html).toContain("<code>a|b`c&#60;/code&#62;</code>");
    expect(html).toContain("&#34;quotes&#34; and &#39;apostrophes&#39;");
    expect(htmlText("<a href='x'>&</a>")).toBe("&#60;a href=&#39;x&#39;&#62;&#38;&#60;/a&#62;");
  });

  it("keeps the example's line feeds, so it reads as indented JSON", () => {
    expect(html).not.toContain("\\u{a}");
    const example = /<section id="type-Order">[\s\S]*?<pre><code>([\s\S]*?)<\/code><\/pre>/.exec(html)?.[1] ?? "";
    expect(example.startsWith("{\n  &#34;id&#34;: ")).toBe(true);
    expect(example.split("\n").length).toBeGreaterThan(3);
  });

  it("shows a description of several lines the way the Markdown page does", () => {
    const md = pages.get("Order.md") ?? "";
    // Markdown keeps the line feeds as soft breaks, and HTML keeps them as white space: both one paragraph.
    expect(md).toContain("\\# not a title\n\\<script\\>");
    expect(html).toContain("<p># not a title\n&#60;script&#62;");
    const mdLines = /# Order\n\n([\s\S]*?)\n\n/.exec(md)?.[1]?.split("\n") ?? [];
    const htmlLines = /<h2>Order<\/h2>\n<p>([\s\S]*?)<\/p>/.exec(html)?.[1]?.split("\n") ?? [];
    expect(htmlLines).toHaveLength(mdLines.length);
    expect(mdLines.length).toBe(HOSTILE.split("\n").length);
  });

  it("holds the same content as the Markdown pages: every type and the same example", () => {
    for (const [name, text] of pages) {
      if (name === DOCS_INDEX) continue;
      const example = /```json\n([\s\S]*?)\n```/.exec(text)?.[1];
      expect(example).toBeDefined();
      expect(html).toContain(`<pre><code>${htmlText(example ?? "")}</code></pre>`);
    }
  });
});

describe("docs config", () => {
  it("takes html as docs.format, and markdown by default", () => {
    expect(config("html").docs?.format).toBe("html");
    expect(parseConfig({ targets: { go: { out: "go" } }, docs: { out: "d" } }, join(ROOT, "strictgen.json")).docs?.format).toBe("markdown");
    expect(() => parseConfig({ targets: { go: { out: "go" } }, docs: { out: "d", format: "pdf" } }, join(ROOT, "strictgen.json"))).toThrow(
      'docs.format: must be one of "markdown", "html"',
    );
  });

  it("refuses a docs folder that is a target's folder or inside an owned one", () => {
    const at = (out: string): unknown => () =>
      parseConfig({ targets: { go: { out: "go" }, typescript: { out: "ts" } }, docs: { out } }, join(ROOT, "strictgen.json"));
    expect(at("go")).toThrow(ConfigError);
    expect(at("go")).toThrow("docs.out: is the same folder as targets.go.out");
    expect(at("ts/docs")).toThrow("docs.out: is inside targets.typescript.out, which is cleared before writing");
    expect(at("docs")).not.toThrow();
  });

  it("marks a header with -- so the HTML comment stays one comment", () => {
    expect(markupHeader("a -- b --> c")).toBe("<!-- a - - b - -> c -->");
    expect(isGenerated(`${markupHeader("x--y")}\nbody`, "x--y")).toBe(true);
  });
});

describe("strictgen docs and examples commands", () => {
  const roots: string[] = [];
  afterEach(() => {
    for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
  });

  function project(extra: object = {}, schemas: Record<string, JsonObject> = { order: orderSchema() }): string {
    const root = mkdtempSync(join(tmpdir(), "strictgen-docs-"));
    roots.push(root);
    mkdirSync(join(root, "schemas"));
    for (const [name, s] of Object.entries(schemas)) writeFileSync(join(root, "schemas", `${name}.json`), JSON.stringify(s));
    writeFileSync(join(root, "strictgen.json"), JSON.stringify({ targets: { typescript: { out: "ts" } }, docs: { out: "docs" }, ...extra }));
    return root;
  }

  function cli(root: string, ...args: string[]): { code: number; out: string[]; err: string[] } {
    const out: string[] = [];
    const err: string[] = [];
    const code = run(args, { cwd: root, env: {}, out: (l) => out.push(l), err: (l) => err.push(l) });
    return { code, out, err };
  }

  it("writes the pages, keeps hand-written files and removes stale generated ones", () => {
    const root = project();
    mkdirSync(join(root, "docs"));
    writeFileSync(join(root, "docs", "README.md"), "# Our contracts\n");
    writeFileSync(join(root, "docs", "Gone.md"), `${markupHeader("Code generated by strictgen. DO NOT EDIT.")}\n\nold\n`);
    expect(cli(root, "docs")).toEqual({ code: EXIT_OK, out: ["Wrote 9 docs files to docs."], err: [] });
    const names = readdirSync(join(root, "docs")).sort();
    expect(names).toContain("README.md");
    expect(names).toContain("Order.md");
    expect(names).not.toContain("Gone.md");
    expect(readFileSync(join(root, "docs", "README.md"), "utf8")).toBe("# Our contracts\n");
    const html = cli(root, "docs", "--format", "html");
    expect(html.code).toBe(EXIT_OK);
    expect(readdirSync(join(root, "docs")).sort()).toEqual(["README.md", "index.html"]);
  });

  it("refuses to overwrite a hand-written page and writes nothing then", () => {
    const root = project();
    mkdirSync(join(root, "docs"));
    writeFileSync(join(root, "docs", "Order.md"), "mine\n");
    const result = cli(root, "docs");
    expect(result.code).toBe(EXIT_FAILED);
    expect(result.err[0]).toMatch(/^error: docs\/Order\.md: output-conflict: a hand written file is in the way/);
    expect(readdirSync(join(root, "docs"))).toEqual(["Order.md"]);
  });

  it("fails as bad config without a docs section, and on an unknown format", () => {
    const root = project({ docs: undefined });
    expect(cli(root, "docs")).toEqual({
      code: EXIT_USAGE,
      out: [],
      err: ['error: strictgen.json: docs: is not set. Add "docs": { "out": "docs/types" } to say where the pages go'],
    });
    expect(cli(project(), "docs", "--format", "pdf").err[0]).toBe('error: --format must be one of markdown, html, not "pdf"');
    expect(existsSync(join(root, "docs"))).toBe(false);
  });

  it("prints valid payloads, the same for the same seed", () => {
    const root = project();
    const first = cli(root, "examples", "Order", "--count", "3", "--seed", "9");
    expect(first.code).toBe(EXIT_OK);
    expect(first.out).toHaveLength(3);
    for (const line of first.out) expect(JSON.parse(line)).toHaveProperty("id");
    expect(cli(root, "examples", "Order", "--count", "3", "--seed", "9")).toEqual(first);
    expect(cli(root, "examples", "Order", "--count", "3", "--seed", "10").out).not.toEqual(first.out);
    const array = cli(root, "examples", "Order", "--count", "3", "--seed", "9", "--array");
    expect(JSON.parse(array.out.join("\n"))).toEqual(first.out.map((l) => JSON.parse(l) as unknown));
  });

  it("prints near misses with the error they cause", () => {
    const result = cli(project(), "examples", "Order", "--invalid", "--count", "5");
    expect(result.code).toBe(EXIT_OK);
    expect(result.out).toHaveLength(5);
    for (const line of result.out) {
      const item = JSON.parse(line) as Record<string, unknown>;
      expect(Object.keys(item)).toEqual(["path", "code", "change", "payload"]);
    }
  });

  it("says so when a type has fewer near misses than asked for", () => {
    const root = project();
    const result = cli(root, "examples", "PaymentBankType", "--invalid", "--count", "50");
    expect(result.code).toBe(EXIT_OK);
    expect(result.out.length).toBeLessThan(50);
    expect(result.err).toEqual([`notice: only ${String(result.out.length)} different near misses of PaymentBankType found, of the 50 asked for`]);
  });

  it("fails cleanly for an unknown type, bad numbers and a type it can't make", () => {
    const root = project();
    expect(cli(root, "examples", "order")).toEqual({ code: EXIT_USAGE, out: [], err: ['error: unknown type "order". Did you mean Order?'] });
    expect(cli(root, "examples").err[0]).toBe("error: examples needs a type, like Order");
    expect(cli(root, "examples", "Order", "--seed", "-1").code).toBe(EXIT_USAGE);
    expect(cli(root, "examples", "Order", "--count", "1.5").err[0]).toBe('error: --count must be a whole number from 1 to 10000, not "1.5"');
    expect(cli(root, "generate", "--invalid").err[0]).toBe("error: --invalid only applies to strictgen examples");
    expect(cli(root, "docs", "--seed", "1").err[0]).toBe("error: --seed only applies to strictgen examples");
    const never = project({}, {
      order: { ...orderSchema(), properties: { id: { type: "string", pattern: "a^b" } }, required: ["id"] },
    });
    expect(cli(never, "examples", "Order")).toEqual({
      code: EXIT_FAILED,
      out: [],
      err: ["error: can't generate a payload for Order at /id: no string found that matches a^b"],
    });
  });
});
